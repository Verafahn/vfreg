fn fitsWidth(value: u64, width: u32) bool {
    if (width >= 64) return true;
    return value < (@as(u64, 1) << @intCast(width));
}

fn storageBytes(size_bits: u32) u32 {
    const bytes = (@as(u64, size_bits) + 7) / 8;
    if (bytes <= 1) return 1;
    var power: u64 = 1;
    while (power < bytes) power <<= 1;
    if (power > std.math.maxInt(u32)) return 4;
    return @intCast(power);
}

fn storageBits(size_bits: u32) u32 {
    return storageBytes(size_bits) * 8;
}

fn naturalAlignment(storage: u32) u64 {
    var alignment: u64 = 1;
    while (alignment < storage and alignment < 16) alignment <<= 1;
    return alignment;
}

