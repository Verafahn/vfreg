//! Generates Zig source code from the SVD memory model.
//!
//! Design choices:
//!   * A register is a `packed struct(uN)` whose bit fields describe the
//!     register layout.  Unused bits become `z_reserve_N: uM = 0`.
//!   * A peripheral is an `extern struct` of register types, with byte array
//!     padding between registers.
//!   * Peripherals with an identical register layout and the same group name
//!     share a type; array/instance names are folded into an `x` placeholder
//!     (for example `GPIOA`/`GPIOB` -> `GPIOx`).
//!   * Every peripheral instance becomes a `*volatile` pointer constant.
//!   * Field values described by `enumeratedValues` become non-exhaustive
//!     enums with an explicit backing integer type.

const std = @import("std");
const model = @import("model.zig");

const Allocator = std.mem.Allocator;

pub fn generate(gpa: Allocator, device: model.Device) Allocator.Error![]u8 {
    var arena_state = std.heap.ArenaAllocator.init(gpa);
    defer arena_state.deinit();

    var out: std.Io.Writer.Allocating = .init(gpa);
    errdefer out.deinit();

    var generator: Generator = .{
        .gpa = gpa,
        .arena = &arena_state,
        .out = &out,
        .device = device,
    };
    try generator.run();
    return out.toOwnedSlice();
}

const Generator = struct {
    gpa: Allocator,
    arena: *std.heap.ArenaAllocator,
    out: *std.Io.Writer.Allocating,
    device: model.Device,

    groups: std.ArrayList(Group) = .empty,
    all_instances: std.ArrayList(Instance) = .empty,
    group_index_by_key: std.StringHashMap(usize) = undefined,
    used_type_names: std.StringHashMap(void) = undefined,
    used_global_names: std.StringHashMap(void) = undefined,
    used_const_names: std.StringHashMap(void) = undefined,
    flat_cache: std.AutoHashMap(*const model.Peripheral, []FlatRegister) = undefined,

    fn a(self: *Generator) Allocator {
        return self.arena.allocator();
    }

    fn run(self: *Generator) Allocator.Error!void {
        const arena = self.a();
        self.group_index_by_key = .init(arena);
        self.used_type_names = .init(arena);
        self.used_global_names = .init(arena);
        self.used_const_names = .init(arena);
        self.flat_cache = .init(arena);

        try self.emitHeader();
        try self.buildGroups();
        try self.assignTypeNames();
        try self.emitTypes();
        try self.emitConstants();
    }

    fn write(self: *Generator, bytes: []const u8) Allocator.Error!void {
        self.out.writer.writeAll(bytes) catch return error.OutOfMemory;
    }

    fn print(self: *Generator, comptime fmt: []const u8, args: anytype) Allocator.Error!void {
        self.out.writer.print(fmt, args) catch return error.OutOfMemory;
    }

    fn emitHeader(self: *Generator) Allocator.Error!void {
        try self.write("//! Generated by vfreg from a CMSIS-SVD description.\n");
        try self.print("//! Device: {s}\n", .{self.device.name});
        if (self.device.vendor) |vendor| try self.print("//! Vendor: {s}\n", .{vendor});
        if (self.device.version) |version| try self.print("//! SVD version: {s}\n", .{version});
        if (self.device.description) |description| {
            try self.print("//!\n//! {s}\n", .{description});
        }
        try self.write("\n");
    }

    // -----------------------------------------------------------------------
    // Peripheral grouping
    // -----------------------------------------------------------------------

    fn buildGroups(self: *Generator) Allocator.Error!void {
        const arena = self.a();

        for (self.device.peripherals) |*peripheral| {
            const flat = try self.flattenPeripheral(peripheral);
            const signature = try self.layoutSignature(flat);
            const hint = try self.typeHint(peripheral);

            const indices: []const []const u8 = if (peripheral.dim) |dim|
                try self.dimIndices(dim)
            else
                &.{};
            const count: usize = if (peripheral.dim) |dim| dim.dim else 1;

            for (0..count) |index| {
                const instance_name = if (peripheral.dim) |dim|
                    try self.expandName(peripheral.name, dim, index, indices)
                else
                    peripheral.name;
                const address = peripheral.base_address + (if (peripheral.dim) |dim|
                    @as(u64, index) * dim.dim_increment
                else
                    0);

                const key = try std.fmt.allocPrint(arena, "{s}\x1f{s}", .{ hint, signature });
                const entry = try self.group_index_by_key.getOrPut(key);
                if (!entry.found_existing) {
                    entry.value_ptr.* = self.groups.items.len;
                    try self.groups.append(arena, .{
                        .hint = hint,
                        .signature = signature,
                        .representative = peripheral,
                    });
                }
                const group_index = entry.value_ptr.*;

                const const_name = try self.uniqueConstName(instance_name);
                const instance: Instance = .{
                    .name = const_name,
                    .base_address = address,
                    .peripheral = peripheral,
                    .group_index = group_index,
                };
                try self.groups.items[group_index].instances.append(arena, instance);
                try self.all_instances.append(arena, instance);
            }
        }
    }

    fn assignTypeNames(self: *Generator) Allocator.Error!void {
        const arena = self.a();
        for (self.groups.items) |*group| {
            const base = try self.groupBaseName(group);
            if (try self.claimTypeName(base)) |name| {
                group.type_name = name;
                continue;
            }
            // A shared `x` placeholder name may already be taken by another
            // layout (for example TIM1/TIM2/TIM3+ have different registers)
            // or the name may collide with the peripheral pointer constant.
            const fallback = try std.fmt.allocPrint(
                arena,
                "{s}_Type",
                .{group.instances.items[0].name},
            );
            group.type_name = try self.uniqueTypeName(fallback);
        }
    }

    fn typeHint(self: *Generator, peripheral: *const model.Peripheral) Allocator.Error![]const u8 {
        if (peripheral.header_struct_name) |name| return name;
        if (peripheral.dim != null) return self.namePatternToTypeName(peripheral.name);
        if (peripheral.group_name) |name| return name;
        return peripheral.name;
    }

    fn groupBaseName(self: *Generator, group: *const Group) Allocator.Error![]const u8 {
        const arena = self.a();
        if (group.representative.header_struct_name) |name| return name;
        if (group.representative.dim != null) {
            return self.namePatternToTypeName(group.representative.name);
        }
        if (group.instances.items.len == 1) {
            return group.instances.items[0].name;
        }

        var prefix = group.instances.items[0].name;
        for (group.instances.items[1..]) |instance| {
            prefix = commonPrefix(prefix, instance.name);
        }
        while (prefix.len > 0) {
            const last = prefix[prefix.len - 1];
            if (last == '_' or std.ascii.isDigit(last)) {
                prefix = prefix[0 .. prefix.len - 1];
            } else break;
        }
        if (prefix.len == 0) prefix = group.hint;
        return std.fmt.allocPrint(arena, "{s}x", .{prefix});
    }

    fn uniqueConstName(self: *Generator, name: []const u8) Allocator.Error![]const u8 {
        const arena = self.a();
        var candidate = name;
        var suffix: usize = 2;
        while (self.used_const_names.contains(candidate)) {
            candidate = try std.fmt.allocPrint(arena, "{s}_{d}", .{ name, suffix });
            suffix += 1;
        }
        try self.used_const_names.put(candidate, {});
        try self.used_global_names.put(candidate, {});
        return candidate;
    }

    fn claimTypeName(self: *Generator, raw_base: []const u8) Allocator.Error!?[]const u8 {
        const arena = self.a();
        const base = try sanitizeTypeName(arena, raw_base);
        if (self.used_type_names.contains(base) or self.used_global_names.contains(base)) {
            return null;
        }
        try self.used_type_names.put(base, {});
        return base;
    }

    fn uniqueTypeName(self: *Generator, raw_base: []const u8) Allocator.Error![]const u8 {
        if (try self.claimTypeName(raw_base)) |name| return name;

        const arena = self.a();
        const base = try sanitizeTypeName(arena, raw_base);
        var candidate = try std.fmt.allocPrint(arena, "{s}_Type", .{base});
        if (try self.claimTypeName(candidate)) |name| return name;

        var suffix: usize = 2;
        while (true) : (suffix += 1) {
            candidate = try std.fmt.allocPrint(arena, "{s}_Type_{d}", .{ base, suffix });
            if (try self.claimTypeName(candidate)) |name| return name;
        }
    }

    // -----------------------------------------------------------------------
    // Flattening clusters and register arrays
    // -----------------------------------------------------------------------

    const FlatRegister = struct {
        name: []const u8,
        address_offset: u64,
        cluster_prefix: []const u8,
        register: *const model.Register,
    };

    const FlatField = struct {
        name: []const u8,
        offset: u64,
        width: u32,
        field_index: usize,
    };

    const Instance = struct {
        name: []const u8,
        base_address: u64,
        peripheral: *const model.Peripheral,
        group_index: usize,
    };

    const Group = struct {
        hint: []const u8,
        signature: []const u8,
        representative: *const model.Peripheral,
        instances: std.ArrayList(Instance) = .empty,
        type_name: []const u8 = "",
    };

    const EmittedRegister = struct {
        flat: FlatRegister,
        type_name: []const u8,
    };

    fn flattenPeripheral(
        self: *Generator,
        peripheral: *const model.Peripheral,
    ) Allocator.Error![]FlatRegister {
        if (self.flat_cache.get(peripheral)) |cached| return cached;

        var list: std.ArrayList(FlatRegister) = .empty;
        try self.walkNodes(peripheral.registers, 0, "", &list);

        std.mem.sort(FlatRegister, list.items, {}, lessThanFlatRegister);
        try self.disambiguateFlatNames(list.items);

        const result = try list.toOwnedSlice(self.a());
        try self.flat_cache.put(peripheral, result);
        return result;
    }

    fn walkNodes(
        self: *Generator,
        nodes: []const model.RegisterNode,
        base_offset: u64,
        prefix: []const u8,
        out: *std.ArrayList(FlatRegister),
    ) Allocator.Error!void {
        for (nodes) |*node| {
            switch (node.*) {
                .register => |*register| {
                    if (register.alternate_register != null) continue;

                    const indices: []const []const u8 = if (register.dim) |dim|
                        try self.dimIndices(dim)
                    else
                        &.{};
                    const count: usize = if (register.dim) |dim| dim.dim else 1;
                    for (0..count) |index| {
                        const name = if (register.dim) |dim|
                            try self.expandName(register.name, dim, index, indices)
                        else
                            register.name;
                        const offset = base_offset + register.address_offset + (if (register.dim) |dim|
                            @as(u64, index) * dim.dim_increment
                        else
                            0);
                        try out.append(self.a(), .{
                            .name = name,
                            .address_offset = offset,
                            .cluster_prefix = prefix,
                            .register = register,
                        });
                    }
                },
                .cluster => |*cluster| {
                    const indices: []const []const u8 = if (cluster.dim) |dim|
                        try self.dimIndices(dim)
                    else
                        &.{};
                    const count: usize = if (cluster.dim) |dim| dim.dim else 1;
                    for (0..count) |index| {
                        const cluster_name = if (cluster.dim) |dim|
                            try self.expandName(cluster.name, dim, index, indices)
                        else
                            cluster.name;
                        const offset = base_offset + cluster.address_offset + (if (cluster.dim) |dim|
                            @as(u64, index) * dim.dim_increment
                        else
                            0);
                        const child_prefix = if (prefix.len == 0)
                            cluster_name
                        else
                            try std.fmt.allocPrint(self.a(), "{s}_{s}", .{ prefix, cluster_name });
                        try self.walkNodes(cluster.children, offset, child_prefix, out);
                    }
                },
            }
        }
    }

    fn disambiguateFlatNames(self: *Generator, registers: []FlatRegister) Allocator.Error!void {
        const arena = self.a();
        var counts: std.StringHashMap(usize) = .init(arena);
        for (registers) |register| {
            const entry = try counts.getOrPut(register.name);
            if (entry.found_existing) {
                entry.value_ptr.* += 1;
            } else {
                entry.value_ptr.* = 1;
            }
        }

        var used: std.StringHashMap(void) = .init(arena);
        for (registers) |*register| {
            if ((counts.get(register.name) orelse 0) > 1) {
                var candidate = if (register.cluster_prefix.len == 0)
                    register.name
                else
                    try std.fmt.allocPrint(arena, "{s}_{s}", .{ register.cluster_prefix, register.name });
                if (used.contains(candidate)) {
                    candidate = try std.fmt.allocPrint(arena, "{s}_{X}", .{ candidate, register.address_offset });
                }
                register.name = candidate;
            }
            if (used.contains(register.name)) {
                register.name = try std.fmt.allocPrint(arena, "{s}_{X}", .{ register.name, register.address_offset });
            }
            try used.put(register.name, {});
        }
    }

    fn layoutSignature(self: *Generator, registers: []const FlatRegister) Allocator.Error![]const u8 {
        var signature: std.Io.Writer.Allocating = .init(self.a());
        const writer = &signature.writer;

        for (registers) |flat| {
            const register = flat.register;
            writer.print("{s}|{X}|{d}|{d}|", .{
                flat.name,
                flat.address_offset,
                register.properties.effectiveSize(),
                @backingInt(register.properties.effectiveAccess()),
            }) catch return error.OutOfMemory;
            if (register.properties.reset_value) |value| {
                writer.print("{X}", .{value}) catch return error.OutOfMemory;
            } else {
                writer.writeByte('-') catch return error.OutOfMemory;
            }
            writer.writeByte('|') catch return error.OutOfMemory;
            if (register.properties.reset_mask) |value| {
                writer.print("{X}", .{value}) catch return error.OutOfMemory;
            } else {
                writer.writeByte('-') catch return error.OutOfMemory;
            }
            writer.writeByte('|') catch return error.OutOfMemory;

            for (register.fields) |field| {
                writer.print("{s}|", .{field.name}) catch return error.OutOfMemory;
                if (field.bit_range) |range| {
                    writer.print("{d}:{d}", .{ range.offset, range.width }) catch return error.OutOfMemory;
                } else {
                    writer.writeByte('-') catch return error.OutOfMemory;
                }
                writer.writeByte('|') catch return error.OutOfMemory;
                if (field.dim) |dim| {
                    writer.print("{d}:{d}:", .{ dim.dim, dim.dim_increment }) catch return error.OutOfMemory;
                    if (dim.dim_index) |index| {
                        writer.writeAll(index) catch return error.OutOfMemory;
                    }
                    writer.writeByte('|') catch return error.OutOfMemory;
                } else {
                    writer.writeAll("-|-|") catch return error.OutOfMemory;
                }
                if (field.access) |access| {
                    writer.print("{d}", .{@backingInt(access)}) catch return error.OutOfMemory;
                } else {
                    writer.writeByte('-') catch return error.OutOfMemory;
                }
                writer.writeByte('|') catch return error.OutOfMemory;

                for (field.enumerated_values) |set| {
                    if (set.usage) |usage| {
                        writer.print("{d}", .{@backingInt(usage)}) catch return error.OutOfMemory;
                    } else {
                        writer.writeByte('-') catch return error.OutOfMemory;
                    }
                    writer.writeByte(':') catch return error.OutOfMemory;
                    for (set.values) |value| {
                        writer.print("{s}:", .{value.name}) catch return error.OutOfMemory;
                        if (value.value) |number| {
                            writer.print("{X}", .{number}) catch return error.OutOfMemory;
                        } else {
                            writer.writeByte('-') catch return error.OutOfMemory;
                        }
                        writer.writeByte(':') catch return error.OutOfMemory;
                        writer.print("{d};", .{@intFromBool(value.is_default)}) catch return error.OutOfMemory;
                    }
                    writer.writeByte('|') catch return error.OutOfMemory;
                }
                writer.writeByte(';') catch return error.OutOfMemory;
            }
            writer.writeByte(';') catch return error.OutOfMemory;
        }

        return signature.toOwnedSlice() catch return error.OutOfMemory;
    }

    // -----------------------------------------------------------------------
    // Type emission
    // -----------------------------------------------------------------------

    fn emitTypes(self: *Generator) Allocator.Error!void {
        for (self.groups.items) |*group| {
            const flat = try self.flattenPeripheral(group.representative);
            var emitted: std.ArrayList(EmittedRegister) = .empty;
            for (flat) |register| {
                const type_name = try self.emitRegisterType(group.type_name, register);
                try emitted.append(self.a(), .{ .flat = register, .type_name = type_name });
            }
            try self.emitPeripheralType(group, emitted.items);
        }
    }

    const EnumMember = struct {
        value: u64,
        ident: []const u8,
    };

    const EnumInfo = struct {
        primary_type: ?[]const u8 = null,
        members: []const EnumMember = &.{},
    };

    fn emitRegisterType(
        self: *Generator,
        peripheral_type_name: []const u8,
        flat: FlatRegister,
    ) Allocator.Error![]const u8 {
        const arena = self.a();
        const register = flat.register;
        const register_type_name = try self.uniqueTypeName(try std.fmt.allocPrint(
            arena,
            "{s}_{s}",
            .{ peripheral_type_name, flat.name },
        ));

        var infos = try arena.alloc(EnumInfo, register.fields.len);
        @memset(infos, .{});
        for (register.fields, 0..) |field, index| {
            infos[index] = try self.genFieldEnums(register_type_name, field);
        }

        try self.print("/// Layout of the {s} register.\n", .{flat.name});
        const size_bits = register.properties.effectiveSize();
        const backing_bits = storageBits(size_bits);
        try self.print("pub const {s} = packed struct(u{d}) {{\n", .{ register_type_name, backing_bits });

        var fields: std.ArrayList(FlatField) = .empty;
        for (register.fields, 0..) |field, field_index| {
            const range = field.bit_range orelse continue;
            const indices: []const []const u8 = if (field.dim) |dim|
                try self.dimIndices(dim)
            else
                &.{};
            const count: usize = if (field.dim) |dim| dim.dim else 1;
            for (0..count) |index| {
                const name = if (field.dim) |dim|
                    try self.expandName(field.name, dim, index, indices)
                else
                    field.name;
                const offset = @as(u64, range.offset) + (if (field.dim) |dim|
                    @as(u64, index) * dim.dim_increment
                else
                    0);
                try fields.append(arena, .{
                    .name = name,
                    .offset = offset,
                    .width = range.width,
                    .field_index = field_index,
                });
            }
        }
        std.mem.sort(FlatField, fields.items, {}, lessThanFlatField);

        var cursor: u64 = 0;
        var reserve_index: usize = 0;
        var used_names: std.StringHashMap(void) = .init(arena);
        var declared_names: std.StringHashMap(void) = .init(arena);
        for (fields.items) |field| {
            try declared_names.put(field.name, {});
        }

        for (fields.items) |field| {
            if (field.offset >= backing_bits) {
                try self.print("    // field {s} lies outside the register\n", .{field.name});
                continue;
            }
            const width = field.width;
            if (field.offset + width > @as(u64, backing_bits)) {
                try self.print("    // field {s} extends beyond the register and was omitted\n", .{field.name});
                continue;
            }
            if (width == 0) continue;

            if (field.offset < cursor) {
                try self.print("    // field {s} overlaps a previous field and was omitted\n", .{field.name});
                continue;
            }

            if (field.offset > cursor) {
                try self.emitPackedReserve(
                    &reserve_index,
                    &used_names,
                    &declared_names,
                    @intCast(field.offset - cursor),
                );
            }

            const name = try uniqueFieldName(arena, &used_names, field.name, field.offset);
            const info = infos[field.field_index];
            try self.emitCommentIndented("    ", register.fields[field.field_index].description);
            try self.print("    {s}: ", .{try self.renderIdent(name)});
            if (info.primary_type) |type_name| {
                try self.write(type_name);
            } else {
                try self.print("u{d}", .{width});
            }
            try self.emitDefault(register, info, field.offset, width);
            try self.write(",\n");

            cursor = field.offset + @as(u64, width);
        }

        if (cursor < @as(u64, backing_bits)) {
            try self.emitPackedReserve(
                &reserve_index,
                &used_names,
                &declared_names,
                @as(u64, backing_bits) - cursor,
            );
        }

        try self.write("};\n\n");
        return register_type_name;
    }

    fn genFieldEnums(
        self: *Generator,
        register_type_name: []const u8,
        field: model.Field,
    ) Allocator.Error!EnumInfo {
        const arena = self.a();
        const range = field.bit_range orelse return .{};
        if (range.width == 0) return .{};

        var read_set: ?*const model.EnumeratedValues = null;
        var write_set: ?*const model.EnumeratedValues = null;
        for (field.enumerated_values, 0..) |*set, index| {
            const usage = set.usage orelse if (index == 0) model.EnumUsage.read else model.EnumUsage.write;
            switch (usage) {
                .read => if (read_set == null) {
                    read_set = set;
                },
                .write => if (write_set == null) {
                    write_set = set;
                },
                .read_write => {
                    if (read_set == null) read_set = set;
                    if (write_set == null) write_set = set;
                },
            }
        }

        const field_name = try stripDimPlaceholder(arena, field.name);
        const base_name = try std.fmt.allocPrint(arena, "{s}_{s}", .{ register_type_name, field_name });

        const read_enum = if (read_set) |set|
            try self.genEnum(base_name, set, range.width)
        else
            null;
        const write_enum = if (write_set) |set| blk: {
            if (read_set != null and set == read_set.?) break :blk null;
            break :blk try self.genEnum(
                try std.fmt.allocPrint(arena, "{s}_Write", .{base_name}),
                set,
                range.width,
            );
        } else null;

        var info: EnumInfo = .{};
        if (read_enum) |generated| {
            info.primary_type = generated.type_name;
            info.members = generated.members;
        } else if (write_enum) |generated| {
            info.primary_type = generated.type_name;
            info.members = generated.members;
        }
        return info;
    }

    const GeneratedEnum = struct {
        type_name: []const u8,
        members: []EnumMember,
    };

    fn genEnum(
        self: *Generator,
        base_name: []const u8,
        set: *const model.EnumeratedValues,
        width: u32,
    ) Allocator.Error!?GeneratedEnum {
        if (width == 0) return null;

        const arena = self.a();
        var values = std.ArrayList(u64).empty;
        var sources = std.ArrayList(*const model.EnumeratedValue).empty;
        var seen_values: std.AutoHashMap(u64, void) = .init(arena);

        for (set.values) |*enumerated_value| {
            const value = enumerated_value.value orelse continue;
            if (!fitsWidth(value, width)) continue;
            if (seen_values.contains(value)) continue;
            try seen_values.put(value, {});
            try values.append(arena, value);
            try sources.append(arena, enumerated_value);
        }
        if (values.items.len == 0) return null;

        const type_name = try self.uniqueTypeName(base_name);
        var members = try arena.alloc(EnumMember, values.items.len);
        var member_names: std.StringHashMap(void) = .init(arena);
        const exhaustive = width < 31 and values.items.len == (@as(usize, 1) << @intCast(width));

        try self.print("/// Enumerated values of {s}.\n", .{set.name orelse base_name});
        try self.print("pub const {s} = enum(u{d}) {{\n", .{ type_name, width });

        for (values.items, 0..) |value, index| {
            const source = sources.items[index];
            try self.emitCommentIndented("    ", source.description);
            const ident = try uniqueEnumMember(arena, &member_names, source.name, value);
            try self.print("    {s} = 0x{X},\n", .{ ident, value });
            members[index] = .{ .value = value, .ident = ident };
        }
        if (!exhaustive) try self.write("    _,\n");
        try self.write("};\n\n");

        return .{ .type_name = type_name, .members = members };
    }

    fn emitPeripheralType(
        self: *Generator,
        group: *const Group,
        registers: []const EmittedRegister,
    ) Allocator.Error!void {
        const arena = self.a();
        try self.print("pub const {s} = extern struct {{\n", .{group.type_name});

        var cursor: u64 = 0;
        var reserve_index: usize = 0;
        var used_names: std.StringHashMap(void) = .init(arena);
        var declared_names: std.StringHashMap(void) = .init(arena);
        for (registers) |emitted| {
            try declared_names.put(emitted.flat.name, {});
        }

        for (registers) |emitted| {
            const flat = emitted.flat;
            const register = flat.register;
            const storage = storageBytes(register.properties.effectiveSize());

            if (flat.address_offset < cursor) {
                try self.print(
                    "    // register {s} at 0x{X} overlaps a previous register and was omitted\n",
                    .{ flat.name, flat.address_offset },
                );
                continue;
            }

            if (flat.address_offset > cursor) {
                try self.emitStructReserve(
                    &reserve_index,
                    &used_names,
                    &declared_names,
                    flat.address_offset - cursor,
                );
            }

            const name = try uniqueFieldName(arena, &used_names, flat.name, flat.address_offset);
            try self.emitCommentIndented("    ", register.description);
            try self.print("    /// Access: {s}\n", .{register.properties.effectiveAccess().label()});

            try self.print("    {s}: {s}", .{ try self.renderIdent(name), emitted.type_name });
            const alignment = naturalAlignment(storage);
            if (flat.address_offset % alignment != 0) {
                try self.write(" align(1)");
            }
            try self.write(",\n");

            cursor = flat.address_offset + storage;
        }

        try self.write("};\n\n");
    }

    fn emitConstants(self: *Generator) Allocator.Error!void {
        for (self.all_instances.items) |instance| {
            const group = &self.groups.items[instance.group_index];
            try self.emitComment(instance.peripheral.description);
            try self.print(
                "pub const {s}: *volatile {s} = @ptrFromInt(0x{X});\n\n",
                .{ try self.renderIdent(instance.name), group.type_name, instance.base_address },
            );
        }
    }

    // -----------------------------------------------------------------------
    // Small emission helpers
    // -----------------------------------------------------------------------

    fn emitComment(self: *Generator, text: ?[]const u8) Allocator.Error!void {
        try self.emitCommentIndented("", text);
    }

    fn emitCommentIndented(self: *Generator, indent: []const u8, text: ?[]const u8) Allocator.Error!void {
        const value = text orelse return;
        if (value.len == 0) return;
        try self.print("{s}/// {s}\n", .{ indent, value });
    }

    fn emitPackedReserve(
        self: *Generator,
        reserve_index: *usize,
        used_names: *std.StringHashMap(void),
        declared_names: *std.StringHashMap(void),
        bits: u64,
    ) Allocator.Error!void {
        const arena = self.a();
        var index = reserve_index.*;
        while (true) {
            const name = try std.fmt.allocPrint(arena, "z_reserve_{d}", .{index});
            if (!used_names.contains(name) and !declared_names.contains(name)) {
                try used_names.put(name, {});
                try self.print("    {s}: u{d} = 0,\n", .{ name, bits });
                reserve_index.* = index + 1;
                return;
            }
            index += 1;
        }
    }

    fn emitStructReserve(
        self: *Generator,
        reserve_index: *usize,
        used_names: *std.StringHashMap(void),
        declared_names: *std.StringHashMap(void),
        bytes: u64,
    ) Allocator.Error!void {
        const arena = self.a();
        var index = reserve_index.*;
        while (true) {
            const name = try std.fmt.allocPrint(arena, "z_reserve_{d}", .{index});
            if (!used_names.contains(name) and !declared_names.contains(name)) {
                try used_names.put(name, {});
                try self.print("    {s}: [{d}]u8,\n", .{ name, bytes });
                reserve_index.* = index + 1;
                return;
            }
            index += 1;
        }
    }

    fn emitDefault(
        self: *Generator,
        register: *const model.Register,
        info: EnumInfo,
        offset: u64,
        width: u32,
    ) Allocator.Error!void {
        const reset = register.properties.reset_value orelse return;
        if (width > 64 or offset > 63 or offset + @as(u64, width) > 64) return;

        const mask: u64 = if (width >= 64)
            std.math.maxInt(u64)
        else
            (@as(u64, 1) << @intCast(width)) - 1;
        const value = (reset >> @intCast(offset)) & mask;

        if (info.primary_type != null) {
            for (info.members) |member| {
                if (member.value == value) {
                    try self.print(" = .{s}", .{member.ident});
                    return;
                }
            }
            try self.print(" = @enumFromInt(0x{X})", .{value});
            return;
        }
        try self.print(" = 0x{X}", .{value});
    }

    fn renderIdent(self: *Generator, name: []const u8) Allocator.Error![]const u8 {
        const arena = self.a();
        if (isBareIdentifier(name) and !isKeyword(name)) return name;

        var out: std.Io.Writer.Allocating = .init(arena);
        const writer = &out.writer;
        writer.writeAll("@\"") catch return error.OutOfMemory;
        for (name) |byte| {
            if (byte == '"' or byte == '\\') {
                writer.writeByte('\\') catch return error.OutOfMemory;
                writer.writeByte(byte) catch return error.OutOfMemory;
            } else if (byte < 0x20 or byte == 0x7f) {
                writer.writeByte('_') catch return error.OutOfMemory;
            } else {
                writer.writeByte(byte) catch return error.OutOfMemory;
            }
        }
        writer.writeByte('"') catch return error.OutOfMemory;
        return out.toOwnedSlice() catch return error.OutOfMemory;
    }

    // -----------------------------------------------------------------------
    // Name expansion
    // -----------------------------------------------------------------------

    fn expandName(
        self: *Generator,
        name: []const u8,
        dim: model.DimElement,
        index: usize,
        indices: []const []const u8,
    ) Allocator.Error![]const u8 {
        _ = dim;
        const arena = self.a();
        const suffix = if (index < indices.len)
            indices[index]
        else
            try std.fmt.allocPrint(arena, "{d}", .{index});

        var out: std.Io.Writer.Allocating = .init(arena);
        var rest = name;
        var replaced = false;
        while (std.mem.indexOf(u8, rest, "%s")) |position| {
            out.writer.writeAll(rest[0..position]) catch return error.OutOfMemory;
            out.writer.writeAll(suffix) catch return error.OutOfMemory;
            rest = rest[position + 2 ..];
            replaced = true;
        }
        out.writer.writeAll(rest) catch return error.OutOfMemory;
        if (!replaced) out.writer.writeAll(suffix) catch return error.OutOfMemory;

        const raw = out.toOwnedSlice() catch return error.OutOfMemory;
        return removeBrackets(arena, raw);
    }

    fn namePatternToTypeName(self: *Generator, name: []const u8) Allocator.Error![]const u8 {
        const arena = self.a();
        var out: std.Io.Writer.Allocating = .init(arena);
        var rest = name;
        var replaced = false;
        while (std.mem.indexOf(u8, rest, "%s")) |position| {
            out.writer.writeAll(rest[0..position]) catch return error.OutOfMemory;
            out.writer.writeByte('x') catch return error.OutOfMemory;
            rest = rest[position + 2 ..];
            replaced = true;
        }
        out.writer.writeAll(rest) catch return error.OutOfMemory;
        if (!replaced) out.writer.writeByte('x') catch return error.OutOfMemory;
        const raw = out.toOwnedSlice() catch return error.OutOfMemory;
        return removeBrackets(arena, raw);
    }

    fn dimIndices(self: *Generator, dim: model.DimElement) Allocator.Error![]const []const u8 {
        const arena = self.a();
        var result: std.ArrayList([]const u8) = .empty;

        if (dim.dim_index) |spec| {
            const parsed = try parseDimIndex(arena, spec);
            for (parsed) |item| {
                if (result.items.len >= dim.dim) break;
                try result.append(arena, item);
            }
        }
        while (result.items.len < dim.dim) {
            try result.append(arena, try std.fmt.allocPrint(arena, "{d}", .{result.items.len}));
        }
        return result.toOwnedSlice(arena);
    }
};

fn lessThanFlatRegister(_: void, lhs: Generator.FlatRegister, rhs: Generator.FlatRegister) bool {
    return lhs.address_offset < rhs.address_offset;
}

fn lessThanFlatField(_: void, lhs: Generator.FlatField, rhs: Generator.FlatField) bool {
    return lhs.offset < rhs.offset;
}

fn commonPrefix(lhs: []const u8, rhs: []const u8) []const u8 {
    var index: usize = 0;
    while (index < lhs.len and index < rhs.len and lhs[index] == rhs[index]) index += 1;
    return lhs[0..index];
}

fn stripDimPlaceholder(arena: Allocator, name: []const u8) Allocator.Error![]const u8 {
    if (std.mem.indexOf(u8, name, "%s")) |position| {
        return std.fmt.allocPrint(arena, "{s}{s}", .{ name[0..position], name[position + 2 ..] });
    }
    return name;
}

fn removeBrackets(arena: Allocator, name: []const u8) Allocator.Error![]const u8 {
    if (std.mem.indexOfAny(u8, name, "[]") == null) return name;
    var out: std.Io.Writer.Allocating = .init(arena);
    for (name) |byte| {
        if (byte == '[' or byte == ']') continue;
        out.writer.writeByte(byte) catch return error.OutOfMemory;
    }
    return out.toOwnedSlice() catch return error.OutOfMemory;
}

fn parseDimIndex(arena: Allocator, spec: []const u8) Allocator.Error![]const []const u8 {
    const text = std.mem.trim(u8, spec, " \t\r\n");
    var result: std.ArrayList([]const u8) = .empty;

    if (std.mem.indexOfScalar(u8, text, ',')) |_| {
        var tokens = std.mem.splitScalar(u8, text, ',');
        while (tokens.next()) |token| {
            const value = std.mem.trim(u8, token, " \t");
            if (value.len != 0) try result.append(arena, value);
        }
        return result.toOwnedSlice(arena);
    }

    if (std.mem.indexOfScalar(u8, text, '-')) |dash| {
        const lhs = std.mem.trim(u8, text[0..dash], " \t");
        const rhs = std.mem.trim(u8, text[dash + 1 ..], " \t");
        if (lhs.len == 1 and rhs.len == 1 and std.ascii.isAlphabetic(lhs[0]) and std.ascii.isAlphabetic(rhs[0])) {
            var code = lhs[0];
            while (code <= rhs[0]) : (code += 1) {
                try result.append(arena, try std.fmt.allocPrint(arena, "{c}", .{code}));
            }
            return result.toOwnedSlice(arena);
        }
        const first = std.fmt.parseInt(u32, lhs, 0) catch return result.toOwnedSlice(arena);
        const last = std.fmt.parseInt(u32, rhs, 0) catch return result.toOwnedSlice(arena);
        var value = first;
        while (value <= last) : (value += 1) {
            try result.append(arena, try std.fmt.allocPrint(arena, "{d}", .{value}));
        }
        return result.toOwnedSlice(arena);
    }

    if (text.len != 0) try result.append(arena, text);
    return result.toOwnedSlice(arena);
}

fn uniqueFieldName(
    arena: Allocator,
    used: *std.StringHashMap(void),
    name: []const u8,
    offset: u64,
) Allocator.Error![]const u8 {
    var candidate = name;
    if (used.contains(candidate)) {
        candidate = try std.fmt.allocPrint(arena, "{s}_{X}", .{ name, offset });
        var suffix: usize = 2;
        while (used.contains(candidate)) {
            candidate = try std.fmt.allocPrint(arena, "{s}_{X}_{d}", .{ name, offset, suffix });
            suffix += 1;
        }
    }
    try used.put(candidate, {});
    return candidate;
}

fn uniqueEnumMember(
    arena: Allocator,
    used: *std.StringHashMap(void),
    name: []const u8,
    value: u64,
) Allocator.Error![]const u8 {
    var raw = name;
    var rendered = try renderIdentAlloc(arena, raw);
    var suffix: usize = 2;
    while (used.contains(rendered)) {
        raw = try std.fmt.allocPrint(arena, "{s}_{X}_{d}", .{ name, value, suffix });
        rendered = try renderIdentAlloc(arena, raw);
        suffix += 1;
    }
    try used.put(rendered, {});
    return rendered;
}

