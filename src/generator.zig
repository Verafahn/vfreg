fn sanitizeTypeName(arena: Allocator, raw: []const u8) Allocator.Error![]const u8 {
    var out: std.Io.Writer.Allocating = .init(arena);
    const writer = &out.writer;
    for (raw) |byte| {
        if (std.ascii.isAlphanumeric(byte) or byte == '_') {
            writer.writeByte(byte) catch return error.OutOfMemory;
        } else {
            writer.writeByte('_') catch return error.OutOfMemory;
        }
    }
    var name = out.toOwnedSlice() catch return error.OutOfMemory;
    if (name.len == 0) return "Unnamed";
    if (std.ascii.isDigit(name[0])) {
        name = try std.fmt.allocPrint(arena, "_{s}", .{name});
    }
    if (isKeyword(name)) {
        name = try std.fmt.allocPrint(arena, "{s}_Type", .{name});
    }
    return name;
}

fn isBareIdentifier(name: []const u8) bool {
    if (name.len == 0) return false;
    if (!std.ascii.isAlphabetic(name[0]) and name[0] != '_') return false;
    for (name[1..]) |byte| {
        if (!std.ascii.isAlphanumeric(byte) and byte != '_') return false;
    }
    return true;
}

